import 'package:cloud_firestore/cloud_firestore.dart';

/// Represents a guided, structured journal entry generated through the Cognitive Restructuring Engine.
class StructuredJournalEntry {
  final String id;
  final String userId;
  
  /// The workflow intent that created this entry (e.g., 'cbt_wizard', 'adhd_guided', 'sleep_dump')
  final String intentId;
  
  /// Somatic/Emotional intensity scale from 0 to 100
  final int intensity;
  
  /// The raw, structured inputs from the user before AI intervention.
  /// Keys should be standardized (e.g., 'facts', 'automatic_thought', 'avoided_task', 'blocker')
  final Map<String, String> rawInputs;
  
  /// The specific cognitive distortion identified by the Gemini Engine (e.g., 'black_and_white_thinking')
  final String? aiDistortionTag;
  
  /// The psychological push or question generated by the AI
  final String? aiSocraticQuestion;
  
  /// The user's final, grounded response (the reframe or the micro-step commitment)
  final String? userReframe;
  
  final DateTime createdAt;
  final DateTime updatedAt;

  StructuredJournalEntry({
    required this.id,
    required this.userId,
    required this.intentId,
    required this.intensity,
    required this.rawInputs,
    this.aiDistortionTag,
    this.aiSocraticQuestion,
    this.userReframe,
    required this.createdAt,
    required this.updatedAt,
  });

  /// Creates a copy of the entry with updated fields (Useful for Riverpod state management)
  StructuredJournalEntry copyWith({
    String? id,
    String? userId,
    String? intentId,
    int? intensity,
    Map<String, String>? rawInputs,
    String? aiDistortionTag,
    String? aiSocraticQuestion,
    String? userReframe,
    DateTime? createdAt,
    DateTime? updatedAt,
  }) {
    return StructuredJournalEntry(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      intentId: intentId ?? this.intentId,
      intensity: intensity ?? this.intensity,
      rawInputs: rawInputs ?? this.rawInputs,
      aiDistortionTag: aiDistortionTag ?? this.aiDistortionTag,
      aiSocraticQuestion: aiSocraticQuestion ?? this.aiSocraticQuestion,
      userReframe: userReframe ?? this.userReframe,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  /// Serializes the object for Firestore or local SQLite storage
  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'userId': userId,
      'intentId': intentId,
      'intensity': intensity,
      'rawInputs': rawInputs,
      'aiDistortionTag': aiDistortionTag,
      'aiSocraticQuestion': aiSocraticQuestion,
      'userReframe': userReframe,
      // Use FieldValue.serverTimestamp() when creating new records in the service layer.
      // This is for updating/saving existing parsed instances.
      'createdAt': Timestamp.fromDate(createdAt),
      'updatedAt': Timestamp.fromDate(updatedAt),
    };
  }

  /// Safely deserializes from NoSQL Maps, providing robust fallbacks for missing data
  factory StructuredJournalEntry.fromMap(Map<String, dynamic> map, String documentId) {
    // Robust date parsing handling both Firestore Timestamps and raw Strings (if coming from local cache)
    DateTime parseDate(dynamic dateValue) {
      if (dateValue == null) return DateTime.now();
      if (dateValue is Timestamp) return dateValue.toDate();
      if (dateValue is String) return DateTime.parse(dateValue);
      return DateTime.now();
    }

    return StructuredJournalEntry(
      id: documentId,
      userId: map['userId'] as String? ?? 'unknown_user',
      intentId: map['intentId'] as String? ?? 'standard_journal',
      intensity: (map['intensity'] as num?)?.toInt() ?? 0,
      // Ensures the map is safely cast to String keys and String values
      rawInputs: Map<String, String>.from(map['rawInputs'] as Map? ?? {}),
      aiDistortionTag: map['aiDistortionTag'] as String?,
      aiSocraticQuestion: map['aiSocraticQuestion'] as String?,
      userReframe: map['userReframe'] as String?,
      createdAt: parseDate(map['createdAt']),
      updatedAt: parseDate(map['updatedAt']),
    );
  }
}